import { NavLink, Outlet, useNavigate } from 'react-router-dom';
import { useAuth } from '../auth';
import { Button } from './ui';

const navItems = [
  { to: '/', label: 'Dashboard', end: true, icon: DashboardIcon },
  { to: '/forms', label: 'Forms', end: false, icon: FormsIcon },
  { to: '/logs', label: 'Logs', end: false, icon: LogsIcon },
  { to: '/settings', label: 'Settings', end: false, icon: SettingsIcon },
];

export default function Layout() {
  const { me, logout } = useAuth();
  const navigate = useNavigate();

  const onLogout = async () => {
    await logout();
    navigate('/login', { replace: true });
  };

  return (
    <div className="flex min-h-full">
      <aside className="fixed inset-y-0 left-0 z-30 hidden w-56 flex-col border-r border-gray-200 bg-white px-4 py-5 dark:border-gray-800 dark:bg-gray-900 md:flex">
        <Wordmark />
        <nav className="mt-8 flex flex-1 flex-col gap-1">
          {navItems.map((item) => (
            <NavLink
              key={item.to}
              to={item.to}
              end={item.end}
              className={({ isActive }) =>
                `flex items-center gap-3 rounded-md px-3 py-2 text-sm font-medium transition-colors ${
                  isActive
                    ? 'bg-indigo-50 text-indigo-700 dark:bg-indigo-500/10 dark:text-indigo-300'
                    : 'text-gray-600 hover:bg-gray-100 hover:text-gray-900 dark:text-gray-400 dark:hover:bg-gray-800 dark:hover:text-gray-100'
                }`
              }
            >
              <item.icon />
              {item.label}
            </NavLink>
          ))}
        </nav>
        <Button variant="ghost" onClick={onLogout} className="justify-start">
          <LogoutIcon />
          Log out
        </Button>
      </aside>

      <div className="flex min-w-0 flex-1 flex-col md:pl-56">
        {/* Mobile top bar */}
        <header className="flex items-center justify-between border-b border-gray-200 bg-white px-4 py-3 dark:border-gray-800 dark:bg-gray-900 md:hidden">
          <Wordmark />
          <div className="flex items-center gap-3">
            <MobileNav />
            <Button variant="ghost" onClick={onLogout} className="!px-2 !py-1 text-xs">
              Log out
            </Button>
          </div>
        </header>

        {me?.defaultPassword && (
          <div className="border-b border-red-200 bg-red-600 px-4 py-2.5 text-center text-sm font-medium text-white">
            You are using the default admin password. Set the{' '}
            <code className="rounded bg-red-800/60 px-1 py-0.5 font-mono">ADMIN_PASSWORD</code> environment
            variable to secure this instance.
          </div>
        )}

        <main className="mx-auto w-full max-w-6xl flex-1 px-4 py-6 sm:px-6 lg:px-8">
          <Outlet />
        </main>
      </div>
    </div>
  );
}

function Wordmark() {
  return (
    <div className="flex items-center gap-2">
      <span className="flex h-7 w-7 items-center justify-center rounded-md bg-indigo-600 text-sm font-bold text-white">
        r
      </span>
      <span className="text-lg font-semibold tracking-tight text-gray-900 dark:text-gray-100">resender</span>
    </div>
  );
}

function MobileNav() {
  return (
    <nav className="flex gap-1">
      {navItems.map((item) => (
        <NavLink
          key={item.to}
          to={item.to}
          end={item.end}
          className={({ isActive }) =>
            `rounded px-2 py-1 text-xs font-medium ${
              isActive
                ? 'bg-indigo-50 text-indigo-700 dark:bg-indigo-500/10 dark:text-indigo-300'
                : 'text-gray-500 dark:text-gray-400'
            }`
          }
        >
          {item.label}
        </NavLink>
      ))}
    </nav>
  );
}

